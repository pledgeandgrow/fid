#!/usr/bin/env python3
"""enc-oracle-tg9.py -- TG9's RVC compression (compiler/nat_enc.fd
nat_rvc_of) against clang's assembler.

Each instruction form the RISC-V encoders of nat_enc.fd write (and the raw
fld/fsd words of nat_ir.fd) is encoded over many registers and immediates
by a generated Fides program (`fid run`), which prints for each the 2-byte
word nat_rvc_of gives, or the 4-byte word when it gives none. The same
instructions are assembled by clang (`zig cc -c`, target
riscv64-linux-musl) with `.option rvc`, where the assembler compresses
whatever has a 2-byte form. The two must agree instruction by instruction:
the same length and the same bytes. Forms the pass keeps at 4 bytes by
rule (a call `jalr ra`, `ebreak`) are assembled under `.option norvc`.

Then scripts/enc-oracle-tg.py (the 4-byte encoders, TG9's Zba/Zbb ones
included) runs too, unless --no-base is given.

Usage: python3 tests/nattools/enc-oracle-tg9.py [--fid release/fid.exe]
       [--zig zig] [--no-base]
Run from the repository root. Writes build/enc-oracle-tg9/; exit status 0
when every form agrees.
"""
import argparse
import os
import struct
import subprocess
import sys

HEAD = '''// Generated by tests/nattools/enc-oracle-tg9.py: "rv|hex length" per form.
use core;
use vec;
use string;
use compiler::nat_enc;

fn hex(v: i64) -> str {
    var digits: str = "0123456789abcdef";
    var out: str = "";
    var i: i64 = 7;
    while i >= 0 {
        var d: i64 = (v >> (i * 4)) & 15;
        out = out + str_slice(digits, d, d + 1);
        i = i - 1;
    }
    return out;
}

fn rvc(e: &NatEnc) -> str {
    var w: i64 = e.code.get(0) | (e.code.get(1) << 8) | (e.code.get(2) << 16) | (e.code.get(3) << 24);
    var c: i64 = nat_rvc_of(w);
    if c >= 0 {
        return hex(c) + " 2";
    }
    return hex(w) + " 4";
}

fn emit(e: &NatEnc) {
    print("rv|" + rvc(e) + "
");
}

fn ints(s: str) -> Vec<i64> {
    var out: Vec<i64> = Vec::new();
    var parts: Vec<str> = str_split(s, ",");
    var i: i64 = 0;
    while i < parts.len() {
        out.push(str_parse_int(parts.get(i)));
        i = i + 1;
    }
    return out;
}

// The forms in the order forms() of the script lists them
fn main() -> i64 {
    var regs: Vec<i64> = ints("@REGS@");
    var imms: Vec<i64> = ints("@IMMS@");
    var shs: Vec<i64> = ints("@SHS@");
    var luis: Vec<i64> = ints("@LUIS@");
    var di: i64 = 0;
    while di < regs.len() {
        var d: i64 = regs.get(di);
        var ai: i64 = 0;
        while ai < regs.len() {
            var a: i64 = regs.get(ai);
            var ii: i64 = 0;
            while ii < imms.len() {
                var imm: i64 = imms.get(ii);
                var e: NatEnc = NatEnc_new();
                rv_addi(&mut e, d, a, imm);
                emit(&e);
                e = NatEnc_new();
                rv_addiw(&mut e, d, a, imm);
                emit(&e);
                e = NatEnc_new();
                rv_andi(&mut e, d, a, imm);
                emit(&e);
                e = NatEnc_new();
                rv_load(&mut e, d, a, imm, 8, true);
                emit(&e);
                e = NatEnc_new();
                rv_store(&mut e, d, a, imm, 8);
                emit(&e);
                e = NatEnc_new();
                rv_load(&mut e, d, a, imm, 4, true);
                emit(&e);
                e = NatEnc_new();
                rv_store(&mut e, d, a, imm, 4);
                emit(&e);
                e = NatEnc_new();
                NatEnc_word(&mut e, ((imm & 0xFFF) << 20) | (a << 15) | (3 << 12) | (d << 7) | 0x07);
                emit(&e);
                e = NatEnc_new();
                NatEnc_word(&mut e, (((imm >> 5) & 0x7F) << 25) | (d << 20) | (a << 15) | (3 << 12) | ((imm & 0x1F) << 7) | 0x27);
                emit(&e);
                ii = ii + 1;
            }
            var si: i64 = 0;
            while si < shs.len() {
                var sh: i64 = shs.get(si);
                var e2: NatEnc = NatEnc_new();
                rv_slli(&mut e2, d, a, sh);
                emit(&e2);
                e2 = NatEnc_new();
                rv_srli(&mut e2, d, a, sh);
                emit(&e2);
                e2 = NatEnc_new();
                rv_srai(&mut e2, d, a, sh);
                emit(&e2);
                si = si + 1;
            }
            var bi: i64 = 0;
            while bi < regs.len() {
                var b: i64 = regs.get(bi);
                var e3: NatEnc = NatEnc_new();
                rv_add(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_sub(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_xor(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_or(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_and(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_addw(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_subw(&mut e3, d, a, b);
                emit(&e3);
                e3 = NatEnc_new();
                rv_mul(&mut e3, d, a, b);
                emit(&e3);
                bi = bi + 1;
            }
            var e4: NatEnc = NatEnc_new();
            rv_jalr(&mut e4, 0, a, 0);
            emit(&e4);
            e4 = NatEnc_new();
            rv_jalr(&mut e4, 0, a, 8);
            emit(&e4);
            ai = ai + 1;
        }
        var li: i64 = 0;
        while li < luis.len() {
            var e5: NatEnc = NatEnc_new();
            rv_lui(&mut e5, d, luis.get(li));
            emit(&e5);
            li = li + 1;
        }
        di = di + 1;
    }
    var ki: i64 = 0;
    while ki < 4 {
        var e6: NatEnc = NatEnc_new();
        rv_jalr(&mut e6, 1, ints("1,5,10,15").get(ki), 0);
        emit(&e6);
        ki = ki + 1;
    }
    var e7: NatEnc = NatEnc_new();
    rv_ebreak(&mut e7);
    emit(&e7);
    e7 = NatEnc_new();
    rv_ecall(&mut e7);
    emit(&e7);
    return 0;
}
'''

REGS = [0, 1, 2, 5, 8, 9, 10, 15, 16, 31]
IMMS = [-2048, -528, -512, -48, -33, -32, -16, -1, 0, 1, 4, 8, 16, 31, 32, 63, 64,
        120, 124, 128, 248, 252, 256, 496, 504, 512, 1020, 1024, 2047]
SHS = [0, 1, 5, 31, 32, 63]
LUIS = [0, 1, 5, 31, 32, 0x10, 0x12345, 0xFFFE0, 0xFFFDF, 0xFFFFF]


def forms():
    """(what, assembly, norvc) for each form, in the order the loops of the
    Fides program (HEAD) emit them."""
    f = []
    for d in REGS:
        for a in REGS:
            for imm in IMMS:
                f.append(('rv_addi(&mut e, %d, %d, %d)' % (d, a, imm), 'addi x%d, x%d, %d' % (d, a, imm), False))
                f.append(('rv_addiw(&mut e, %d, %d, %d)' % (d, a, imm), 'addiw x%d, x%d, %d' % (d, a, imm), False))
                f.append(('rv_andi(&mut e, %d, %d, %d)' % (d, a, imm), 'andi x%d, x%d, %d' % (d, a, imm), False))
                for size, l, s in [(8, 'ld', 'sd'), (4, 'lw', 'sw')]:
                    f.append(('rv_load(&mut e, %d, %d, %d, %d, true)' % (d, a, imm, size),
                              '%s x%d, %d(x%d)' % (l, d, imm, a), False))
                    f.append(('rv_store(&mut e, %d, %d, %d, %d)' % (d, a, imm, size),
                              '%s x%d, %d(x%d)' % (s, d, imm, a), False))
                f.append(('NatEnc_word(&mut e, ((%d & 0xFFF) << 20) | (%d << 15) | (3 << 12) | (%d << 7) | 0x07)'
                          % (imm, a, d), 'fld f%d, %d(x%d)' % (d, imm, a), False))
                f.append(('NatEnc_word(&mut e, (((%d >> 5) & 0x7F) << 25) | (%d << 20) | (%d << 15) | (3 << 12) | ((%d & 0x1F) << 7) | 0x27)'
                          % (imm, d, a, imm), 'fsd f%d, %d(x%d)' % (d, imm, a), False))
            for sh in SHS:
                for op in ['slli', 'srli', 'srai']:
                    f.append(('rv_%s(&mut e, %d, %d, %d)' % (op, d, a, sh), '%s x%d, x%d, %d' % (op, d, a, sh), False))
            for b in REGS:
                for op in ['add', 'sub', 'xor', 'or', 'and', 'addw', 'subw', 'mul']:
                    f.append(('rv_%s(&mut e, %d, %d, %d)' % (op, d, a, b), '%s x%d, x%d, x%d' % (op, d, a, b), False))
            f.append(('rv_jalr(&mut e, 0, %d, 0)' % a, 'jalr x0, 0(x%d)' % a, False))
            f.append(('rv_jalr(&mut e, 0, %d, 8)' % a, 'jalr x0, 8(x%d)' % a, False))
        for imm20 in LUIS:
            f.append(('rv_lui(&mut e, %d, %d)' % (d, imm20), 'lui x%d, %d' % (d, imm20), False))
    # kept at 4 bytes by rule, though RVC has a form (c.jalr, c.ebreak)
    for a in [1, 5, 10, 15]:
        f.append(('rv_jalr(&mut e, 1, %d, 0)' % a, 'jalr x1, 0(x%d)' % a, True))
    f.append(('rv_ebreak(&mut e)', 'ebreak', True))
    f.append(('rv_ecall(&mut e)', 'ecall', False))
    return f


def elf_text(path):
    data = open(path, 'rb').read()
    shoff = struct.unpack_from('<Q', data, 0x28)[0]
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 0x3A)

    def sh(i):
        return struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * shentsize)
    strtab = sh(shstrndx)
    for i in range(shnum):
        s = sh(i)
        name_off = strtab[4] + s[0]
        name = data[name_off:data.index(b'\0', name_off)].decode()
        if name == '.text':
            return data[s[4]:s[4] + s[5]]
    raise SystemExit('no .text in ' + path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fid', default='release/fid.exe' if os.name == 'nt' else 'release/fid')
    ap.add_argument('--zig', default='zig')
    ap.add_argument('--no-base', action='store_true')
    args = ap.parse_args()
    out = os.path.join('build', 'enc-oracle-tg9')
    os.makedirs(out, exist_ok=True)
    fs = forms()
    def csv(v):
        return ','.join(str(x) for x in v)
    prog = [HEAD.replace('@REGS@', csv(REGS)).replace('@IMMS@', csv(IMMS))
            .replace('@SHS@', csv(SHS)).replace('@LUIS@', csv(LUIS))]
    src = os.path.join(out, 'oracle.fd')
    open(src, 'w', newline='\n').write(''.join(prog))
    r = subprocess.run([args.fid, 'run', src], capture_output=True, text=True)
    lines = [l for l in r.stdout.splitlines() if l.startswith('rv|')]
    if len(lines) != len(fs):
        sys.stderr.write(r.stdout[-2000:] + r.stderr[-2000:])
        raise SystemExit('the program printed %d of %d forms' % (len(lines), len(fs)))
    ours = []
    for line in lines:
        hexw, n = line.split('|')[1].split()
        ours.append((int(hexw, 16), int(n)))
    s_path = os.path.join(out, 'rv.s')
    o_path = os.path.join(out, 'rv.o')
    with open(s_path, 'w', newline='\n') as fh:
        fh.write('.text\n.option rvc\n')
        for _, asm, norvc in fs:
            if norvc:
                fh.write('.option push\n.option norvc\n%s\n.option pop\n' % asm)
            else:
                fh.write(asm + '\n')
    r2 = subprocess.run([args.zig, 'cc', '-target', 'riscv64-linux-musl', '-c', s_path, '-o', o_path],
                        capture_output=True, text=True)
    if r2.returncode != 0:
        sys.stderr.write(r2.stderr)
        raise SystemExit('the assembler refused ' + s_path)
    text = elf_text(o_path)
    bad = 0
    short = 0
    p = 0
    for (call, asm, _), (w, n) in zip(fs, ours):
        if p + 2 > len(text):
            print('MISMATCH the assembler output ends before %s' % asm)
            bad += 1
            break
        lo = struct.unpack_from('<H', text, p)[0]
        if (lo & 3) != 3:
            theirs, tn = lo, 2
        else:
            theirs, tn = struct.unpack_from('<I', text, p)[0], 4
        p += tn
        if n == 2:
            short += 1
        if tn != n or theirs != w:
            bad += 1
            print('MISMATCH %-28s ours %0*x (%d bytes)  clang %0*x (%d bytes)   %s'
                  % (asm, 2 * n, w, n, 2 * tn, theirs, tn, call))
    print('rvc oracle: %d forms, %d in 2 bytes, %d mismatches' % (len(fs), short, bad))
    if not args.no_base:
        here = os.path.dirname(os.path.abspath(__file__))
        base = os.path.join(here, '..', '..', 'scripts', 'enc-oracle-tg.py')
        r3 = subprocess.run([sys.executable, base, '--fid', args.fid, '--zig', args.zig])
        if r3.returncode != 0:
            print('scripts/enc-oracle-tg.py: %d mismatches' % r3.returncode)
            bad += r3.returncode
    return min(bad, 125)


if __name__ == '__main__':
    sys.exit(main())
