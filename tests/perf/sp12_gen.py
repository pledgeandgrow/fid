#!/usr/bin/env python3
"""SP12: write a Fid program whose `work` function has N groups of
statements, for tests/perf/sp12_scaling.sh.

Each group makes the patterns whose lowering cost used to grow with the
length of the whole function, once per candidate:
  - an owned string kept in a second variable (Lowerer_rc_move_last /
    Lowerer_last_use, and the body's defer check it made each time),
  - a string copied and dropped in the same statement list (the
    Str_dup / Str_drop pairs of lw_rc_cancel_pairs, lw_rc_value_used),
  - a Vec shared for a temporary that is only read (lw_rc_cancel_share,
    lw_rc_use_count),
  - a local Vec that stays in the function (lw_rc_stack_vecs_fn: each one's
    drops were rewritten by a scan of the whole function).
The program prints one checksum line, the same for every N it is run with
when N is the same: `sum <n> <total>`.

With --no-place-copy the `var c<i>: str = base;` lines are left out: a
copy of a place is checked by Lowerer_readonly_copy_in against the rest of
its block (cowcheck's cow_first_change / cow_written_back), still a scan
per copy (SP12 left it).

usage: sp12_gen.py N [--no-place-copy] > out.fd
       sp12_gen.py N --expect      (the line the program prints)
"""
import sys


def main():
    n = int(sys.argv[1])
    place_copy = "--no-place-copy" not in sys.argv[2:]
    if "--expect" in sys.argv[2:]:
        # what the program prints: work(1) computed here
        total = 1
        base_len = len("b1")
        for i in range(n):
            total = total + len("a" + str(i)) + base_len
            total = total + 2 + i + 1
        sys.stdout.write("sum %d %d\n" % (n, total))
        return
    out = []
    w = out.append
    w("// generated by tests/perf/sp12_gen.py %d (SP12 lowering scaling)" % n)
    w("fn keep_len(s: str) -> i64 {")
    w("    return str_len(s);")
    w("}")
    w("")
    w("fn work(seed: i64) -> i64 {")
    w("    var total: i64 = seed;")
    w("    var base: str = \"b\" + int_to_str(seed);")
    w("    var shared: Vec<i64> = Vec::new();")
    w("    shared.push(seed);")
    for i in range(n):
        w("    var s%d: str = \"a\" + int_to_str(%d);" % (i, i))
        w("    var t%d: str = s%d;" % (i, i))
        if place_copy:
            w("    var c%d: str = base;" % i)
            w("    total = total + keep_len(t%d) + keep_len(c%d);" % (i, i))
        else:
            w("    total = total + keep_len(t%d) + keep_len(base);" % i)
        w("    var v%d: Vec<i64> = Vec::new();" % i)
        w("    v%d.push(%d);" % (i, i))
        w("    v%d.push(total %% 7);" % i)
        w("    var r%d: Vec<i64> = shared;" % i)
        w("    total = total + v%d.len() + v%d.get(0) + r%d.len();" % (i, i, i))
    w("    return total;")
    w("}")
    w("")
    w("fn main() {")
    w("    print(\"sum %d \" + int_to_str(work(1)));" % n)
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
