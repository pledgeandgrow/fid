PRELUDE = """\
// Generated by scripts/verify/own_diff.py (VF11): programs of
// scripts/verify/own_model.py's calculus; each m<k>() prints what the
// model's value run reads, then main prints #<k>.

struct Bx {
    n: i64,
    kids: Vec<Bx>,
}

struct Pr {
    f: Bx,
    g: Bx,
}

enum Ob {
    Nb,
    Sb(Bx),
}

fn bx_show(b: &Bx) -> str {
    var s: str = "(" + int_to_str(b.n);
    var i: i64 = 0;
    while i < b.kids.len() {
        s = s + " " + bx_show(&b.kids.get(i));
        i = i + 1;
    }
    return s + ")";
}

fn pr_show(p: &Pr) -> str {
    return "[" + bx_show(&p.f) + " " + bx_show(&p.g) + "]";
}

fn ob_show(o: &Ob) -> str {
    match o {
        Ob::Nb => { return "none"; }
        Ob::Sb(v) => { return "some" + bx_show(&v); }
    }
    return "?";
}
"""


class Untranslatable(Exception):
    pass


# ---------------------------------------------------------------- values
def fmt_box(v):
    n, kids = v
    return "(" + str(n) + "".join(" " + fmt_box(k) for k in kids) + ")"


def fmt_obs(o):
    """The line a model read prints in the Fides translation."""
    if isinstance(o, tuple) and o and o[0] == "st":
        return "[" + fmt_box(o[1]) + " " + fmt_box(o[2]) + "]"
    if isinstance(o, tuple) and o and o[0] == "en":
        return "none" if o[1] is None else "some" + fmt_box(o[1])
    if isinstance(o, tuple) and o and o[0] == "count":
        return str(o[1])
    return fmt_box(o)


# ---------------------------------------------------------------- translation
class Tr:
    """Translates one statement list. Scopes map a declared name to its
    kind; a reference's kind is "ref" or "refmut" (Fides gives a reference
    variable one type, so rebinding r from &x to &mut y does not
    translate)."""

    def __init__(self, params=None):
        self.scopes = [dict(params or {})]
        self.out = []

    def kind(self, n):
        for sc in reversed(self.scopes):
            if n in sc:
                return sc[n]
        raise Untranslatable("undeclared " + n)

    def val(self, n):
        """A box name used as a value (it is read: the lowering dups it
        where it is kept)."""
        return "*" + n if self.kind(n) in ("ref", "refmut") else n

    def place(self, n):
        """A box name as the target of an assignment."""
        return "*" + n if self.kind(n) in ("ref", "refmut") else n

    def shown(self, n):
        return "bx_show(&*%s)" % n if self.kind(n) in ("ref", "refmut") else "bx_show(&%s)" % n

    def emit(self, line, depth):
        self.out.append("    " * depth + line)

    def stmts(self, prog, depth):
        for st in prog:
            self.stmt(st, depth)

    def stmt(self, st, d):
        k = st[0]
        e = self.emit
        cur = self.scopes[-1]
        if k == "new":
            e("var %s: Bx = %s;" % (st[1], NEW), d)
            cur[st[1]] = "box"
        elif k == "copy":
            e("var %s: Bx = %s;" % (st[1], self.val(st[2])), d)
            cur[st[1]] = "box"
        elif k == "setnew":
            e("%s = %s;" % (self.place(st[1]), NEW), d)
        elif k == "set":
            e("%s = %s;" % (self.place(st[1]), self.val(st[2])), d)
        elif k == "write":
            e("%s.n = %s.n + 1;" % (st[1], st[1]), d)
        elif k == "read":
            e("println(%s);" % self.shown(st[1]), d)
        elif k == "push":
            e("%s.kids.push(%s);" % (st[1], self.val(st[2])), d)
        elif k == "take":
            e("var %s: Bx = %s.kids.pop();" % (st[2], st[1]), d)
            cur[st[2]] = "box"
        elif k in ("bor", "rebor"):
            rn = om.refname(st)
            want = "refmut" if st[2] else "ref"
            amp = "&mut " if st[2] else "&"
            if k == "bor":
                e("var %s: %sBx = %s%s;" % (rn, amp, amp, st[1]), d)
                cur[rn] = want
            else:
                if self.kind(rn) != want:
                    raise Untranslatable("%s changes from %s to %s" % (rn, self.kind(rn), want))
                e("%s = %s%s;" % (rn, amp, st[1]), d)
        elif k == "call":
            e("f%d(&mut %s);" % (st[1], st[2]), d)
        elif k == "block":
            e("{", d)
            self.scopes.append({})
            self.stmts(st[1], d + 1)
            self.scopes.pop()
            e("}", d)
        # struct
        elif k == "mkst":
            e("var %s: Pr = Pr { f: %s, g: %s };" % (st[1], self.val(st[2]), self.val(st[3])), d)
            cur[st[1]] = "pr"
        elif k == "cpst":
            e("var %s: Pr = %s;" % (st[1], st[2]), d)
            cur[st[1]] = "pr"
        elif k == "asst":
            e("%s = %s;" % (st[1], st[2]), d)
        elif k == "getf":
            e("var %s: Bx = %s.%s;" % (st[1], st[2], FIELD[st[3]]), d)
            cur[st[1]] = "box"
        elif k == "setf":
            e("%s.%s = %s;" % (st[1], FIELD[st[2]], self.val(st[3])), d)
        elif k == "wrf":
            f = "%s.%s" % (st[1], FIELD[st[2]])
            e("%s.n = %s.n + 1;" % (f, f), d)
        elif k == "readst":
            e("println(pr_show(&%s));" % st[1], d)
        # enum
        elif k == "mksome":
            e("var %s: Ob = Ob::Sb(%s);" % (st[1], self.val(st[2])), d)
            cur[st[1]] = "ob"
        elif k == "mknone":
            e("var %s: Ob = Ob::Nb;" % st[1], d)
            cur[st[1]] = "ob"
        elif k == "cpen":
            e("var %s: Ob = %s;" % (st[1], st[2]), d)
            cur[st[1]] = "ob"
        elif k == "setsome":
            e("%s = Ob::Sb(%s);" % (st[1], self.val(st[2])), d)
        elif k == "setnone":
            e("%s = Ob::Nb;" % st[1], d)
        elif k == "unwrap":
            e("var %s: Bx = match %s { Ob::Sb(v) => v, Ob::Nb => %s };" % (st[1], st[2], NEW), d)
            cur[st[1]] = "box"
        elif k == "readen":
            e("println(ob_show(&%s));" % st[1], d)
        # closure
        elif k == "mkclo":
            e("val %s = fn() -> str { return bx_show(&%s); };" % (st[1], st[2]), d)
            cur[st[1]] = "clo"
        elif k == "cpclo":
            e("val %s = %s;" % (st[1], st[2]), d)
            cur[st[1]] = "clo"
        elif k == "callc":
            e("println(%s());" % st[1], d)
        # rc
        elif k == "mkrc":
            e("var %s: Rc<Bx> = Rc::new(%s);" % (st[1], self.val(st[2])), d)
            cur[st[1]] = "rc"
        elif k == "cprc":
            e("var %s: Rc<Bx> = %s.clone();" % (st[1], st[2]), d)
            cur[st[1]] = "rc"
        elif k == "asrc":
            e("%s = %s.clone();" % (st[1], st[2]), d)
        elif k == "rcget":
            e("var %s: Bx = %s.get();" % (st[1], st[2]), d)
            cur[st[1]] = "box"
        elif k == "rccount":
            e("println(int_to_str(%s.count()));" % st[1], d)
        elif k == "rcread":
            e("println(bx_show(&%s.get()));" % st[1], d)
        else:
            raise Untranslatable("statement " + k)


def callees():
    """f0..f4 of own_model.CALLEES, each fn fk(p: &mut Bx)."""
    lines = []
    for i, body in enumerate(om.CALLEES):
        t = Tr({"p": "refmut"})
        t.stmts(body, 1)
        lines.append("fn f%d(p: &mut Bx) {" % i)
        lines += t.out
        lines.append("}")
        lines.append("")
    return lines


def translate(prog):
    """-> the body lines of one program (raises Untranslatable)."""
    t = Tr()
    t.stmts(prog, 1)
    return t.out


def build_file(items):
    """items: [(id, body lines)] -> (text, {id: (first line, last line)})."""
    lines = PRELUDE.rstrip("\n").split("\n") + [""] + callees()
    spans = {}
    for pid, body in items:
        start = len(lines) + 1
        lines.append("fn m%d() {" % pid)
        lines += body
        lines.append("}")
        spans[pid] = (start, len(lines))
        lines.append("")
    lines.append("fn main() -> i64 {")
    for pid, _ in items:
        lines.append("    m%d();" % pid)
        lines.append('    println("#%d");' % pid)
    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines) + "\n", spans


# ---------------------------------------------------------------- running fid
def run_fid(fid, args, cwd, timeout):
    try:
        p = subprocess.run([fid] + args, cwd=cwd, capture_output=True, text=True,
                           timeout=timeout, encoding="utf-8", errors="replace")
        return p.returncode, p.stdout, p.stderr
    except subprocess.TimeoutExpired:
        return 124, "", "timeout after %d s" % timeout


def clean_stdout(s):
    keep = []
    for ln in s.splitlines():
        ln = ln.rstrip("\r")
        if ln.startswith("Built native executable") or ln.startswith("Reused cached artifact"):
            continue
        if ln.startswith("[build]") or ln.startswith("[prof]") or ln.startswith("[main]") \
                or ln.startswith("[ccompile]"):
            continue
        keep.append(ln)
    return keep


def split_by_marker(lines, ids):
    """-> ({id: [lines]}, first id whose marker is missing or None)"""
    got = {}
    cur = []
    want = list(ids)
    i = 0
    for ln in lines:
        if i < len(want) and ln == "#%d" % want[i]:
            got[want[i]] = cur
            cur = []
            i += 1
        else:
            cur.append(ln)
    missing = want[i] if i < len(want) else None
    if missing is not None:
        got[missing] = cur
    return got, missing


LEAK_RE = re.compile(r"^\s*(\d+) bytes in\s+(\d+) block\(s\): (.*), allocated at (.*):(\d+)\s*$")


def leak_sites(stderr, spans, fname):
    """-> ({id: [report lines]}, [report lines not on a program's line])"""
    per, other = {}, []
    for ln in stderr.splitlines():
        m = LEAK_RE.match(ln)
        if not m:
            continue
        line = int(m.group(5))
        at = m.group(4).replace("\\", "/")
        hit = None
        if at.endswith(fname):
            for pid, (a, b) in spans.items():
                if a <= line <= b:
                    hit = pid
                    break
        if hit is None:
            other.append(ln.strip())
        else:
            per.setdefault(hit, []).append(ln.strip())
    return per, other


# ---------------------------------------------------------------- selection
REJECT_KINDS = ("borrowed", "&x while", "escape", "change through a shared borrow")


def flat_stmts(prog):
    out = []
    for st in prog:
        if st[0] == "block":
            out.append(("{",))
            out += flat_stmts(st[1])
            out.append(("}",))
        else:
            out.append(st)
    return out


def features(prog, level=2):
    """What a program exercises: level 0 the kinds of its statements, 1 its
    statements, 2 the pairs of kinds of consecutive statements."""
    fl = flat_stmts(prog)
    if level == 0:
        return set(st[0] for st in fl)
    if level == 1:
        return set(fl)
    return set((x[0], y[0]) for x, y in zip(fl, fl[1:]))


def pick(size, ext, per, want_rejected):
    """-> (accepted [(prog, expected lines)], skipped counts, rejected [(prog, why)])"""
    acc = []
    skipped = {"panic": 0, "untranslatable": 0, "empty": 0, "model fail": 0}
    for prog, got, want in om.accepted(size, ext=ext):
        if not prog:
            skipped["empty"] += 1
            continue
        if isinstance(got, Exception):
            skipped["model fail"] += 1
            continue
        if "panic" in want:
            skipped["panic"] += 1
            continue
        acc.append((prog, [fmt_obs(o) for o in want]))
    chosen = []
    if acc and per != 0:
        # First the programs that bring a statement, or a pair of
        # consecutive statements, no chosen program has yet (so every
        # statement of the feature is run, reads included), longest
        # programs first; then every k-th of the rest.
        taken = set()
        order = sorted(range(len(acc)), key=lambda i: (-len(flat_stmts(acc[i][0])), i))
        for level in (0, 1, 2):  # statement kinds, then statements, then pairs
            seen = set()
            for i in taken:
                seen |= features(acc[i][0], level)
            for i in order:
                if per > 0 and len(chosen) >= max(1, per // 2):
                    break
                if i in taken or (level == 2 and not acc[i][1]):
                    continue
                fs = features(acc[i][0], level)
                if fs - seen:
                    try:
                        translate(acc[i][0])
                    except Untranslatable:
                        continue
                    seen |= fs
                    taken.add(i)
                    chosen.append(acc[i])
        # the rest from the programs that read something (all of them with
        # --per -1)
        pool = [i for i in range(len(acc)) if i not in taken and (acc[i][1] or per < 0)]
        if per > 0 and len(pool) < per - len(chosen):
            pool = [i for i in range(len(acc)) if i not in taken]
        step = max(1, len(pool) // max(1, per - len(chosen))) if per > 0 else 1
        for j in range(0, len(pool), step):
            i = pool[j]
            prog, exp = acc[i]
            try:
                translate(prog)
            except Untranslatable:
                skipped["untranslatable"] += 1
                continue
            chosen.append((prog, exp))
            if per > 0 and len(chosen) >= per:
                break
    rej = []
    if want_rejected > 0:
        allr = []
        for prog in om.programs(size, ext=ext):
            try:
                om.check(prog, frozenset())
            except om.Reject as e:
                if any(str(e).startswith(r) for r in REJECT_KINDS):
                    allr.append((prog, str(e)))
        step = max(1, len(allr) // want_rejected)
        for i in range(0, len(allr), step):
            prog, why = allr[i]
            try:
                translate(prog)
            except Untranslatable:
                continue
            rej.append((prog, why))
            if len(rej) >= want_rejected:
                break
    return acc, chosen, skipped, rej


# ---------------------------------------------------------------- the check
class Runner:
    def __init__(self, a, work):
        self.a = a
        self.work = work
        self.n_files = 0
        self.processes = 0

    def fid(self, args, timeout=None):
        self.processes += 1
        return run_fid(self.a.fid, args, self.work, timeout or self.a.timeout)

    def write(self, items, tag):
        self.n_files += 1
        name = "own_%s_%d.fd" % (tag, self.n_files)
        text, spans = build_file(items)
        path = os.path.join(self.work, name)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return name, spans

    def rejected_by_fid(self, items, tag):
        """Split items until each program fid rejects is found alone.
        -> (kept items, {id: first error line})"""
        name, _ = self.write(items, tag)
        rc, out, err = self.fid(["check", name])
        if rc == 0:
            return items, {}
        if len(items) == 1:
            msg = [ln for ln in (err + "\n" + out).splitlines()
                   if not ln.startswith("[") and "error" in ln.lower()]
            return [], {items[0][0]: (msg[0].strip() if msg else "rejected (exit %d)" % rc)}
        h = len(items) // 2
        k1, r1 = self.rejected_by_fid(items[:h], tag)
        k2, r2 = self.rejected_by_fid(items[h:], tag)
        r1.update(r2)
        return k1 + k2, r1


def check_feature(R, feat, ext, rep):
    a = R.a
    t0 = time.time()
    allacc, chosen, skipped, rej = pick(a.size, ext, a.per, a.rejected)
    fr = {"feature": feat, "accepted": len(allacc), "checked": 0, "skipped": skipped,
          "fid_rejects": [], "mismatch": [], "leaks": [], "faults": [],
          "other_leaks": [], "build_errors": [], "rejected_sample": len(rej),
          "rejected_but_accepted": []}
    progs = {}
    items = []
    for i, (prog, exp) in enumerate(chosen):
        pid = len(rep["programs"])
        rep["programs"].append({"id": pid, "feature": feat, "program": om.show(prog),
                                "expected": exp})
        progs[pid] = (prog, exp)
        items.append((pid, translate(prog)))
    for b in range(0, len(items), a.batch):
        batch = items[b:b + a.batch]
        batch, rejs = R.rejected_by_fid(batch, feat)
        for pid, msg in sorted(rejs.items()):
            fr["fid_rejects"].append({"id": pid, "program": om.show(progs[pid][0]), "error": msg})
        if not batch:
            continue
        name, spans = R.write(batch, feat)
        ids = [pid for pid, _ in batch]
        fr["checked"] += len(ids)
        for mode in a.modes:
            args = ["run", name] + {"run": [], "leaks": ["--leaks"],
                                    "checked": ["--checked-alloc"]}[mode]
            rc, out, err = R.fid(args)
            if rc != 0 and "#%d" % ids[0] not in out and mode != "run" and \
                    ("C compilation failed" in err or "build failed" in err):
                fr["build_errors"].append({"mode": mode, "file": name,
                                           "error": (err.strip().splitlines() or ["?"])[-1][:300]})
                continue
            got, missing = split_by_marker(clean_stdout(out), ids)
            for pid in ids:
                prog, exp = progs[pid]
                lines = got.get(pid)
                if lines is None:
                    continue  # after the program that stopped the run
                if pid == missing:
                    tail = [ln for ln in err.splitlines() if ln.strip()][-3:]
                    fr["faults"].append({"id": pid, "mode": mode, "program": om.show(prog),
                                         "exit": rc, "printed": lines, "stderr": tail})
                elif lines != exp:
                    fr["mismatch"].append({"id": pid, "mode": mode, "program": om.show(prog),
                                           "expected": exp, "printed": lines})
            if missing is not None:
                # the rest of the batch did not run in this mode
                fr.setdefault("not_reached", 0)
                fr["not_reached"] += len(ids) - ids.index(missing) - 1
            if mode == "leaks":
                per, other = leak_sites(err, spans, name)
                for pid, sites in sorted(per.items()):
                    fr["leaks"].append({"id": pid, "program": om.show(progs[pid][0]),
                                        "sites": sites})
                if other:
                    fr["other_leaks"].append({"file": name, "sites": other})
                if "every block was freed" not in err and not per and not other and missing is None:
                    fr["other_leaks"].append({"file": name, "sites": ["no leak report"]})
    for prog, why in rej:
        name, _ = R.write([(0, translate(prog))], feat + "_rej")
        rc, out, err = R.fid(["check", name])
        if rc == 0:
            entry = {"program": om.show(prog), "model": why}
            if "checked" in a.modes:
                rc2, out2, err2 = R.fid(["run", name, "--checked-alloc"])
                entry["checked_alloc_exit"] = rc2
                entry["stderr"] = [ln for ln in err2.splitlines() if ln.strip()][-3:]
            fr["rejected_but_accepted"].append(entry)
    fr["seconds"] = round(time.time() - t0, 1)
    return fr


def summary_line(fr):
    return ("%-8s accepted %6d, checked %4d, fid rejects %3d, value mismatches %3d, "
            "programs leaking %3d, faults %3d, build errors %d, rejected-but-accepted %d/%d (%.0f s)"
            % (fr["feature"], fr["accepted"], fr["checked"], len(fr["fid_rejects"]),
               len(fr["mismatch"]), len(fr["leaks"]), len(fr["faults"]),
               len(fr["build_errors"]), len(fr["rejected_but_accepted"]),
               fr["rejected_sample"], fr["seconds"]))


# ---------------------------------------------------------------- self-test
def self_test():
    """The translator and the expected output on fixed programs (no fid)."""
    bad = 0
    cases = [
        ([("new", "a"), ("write", "a"), ("copy", "b", "a"), ("push", "a", "b"),
          ("read", "a"), ("read", "b")],
         ["    var a: Bx = Bx { n: 0, kids: Vec::new() };", "    a.n = a.n + 1;",
          "    var b: Bx = a;", "    a.kids.push(b);", "    println(bx_show(&a));",
          "    println(bx_show(&b));"],
         ["(1 (1))", "(1)"], None),
        ([("new", "a"), ("bor", "a", True), ("write", "r"), ("set", "r", "r"), ("read", "r")],
         ["    var a: Bx = Bx { n: 0, kids: Vec::new() };", "    var r: &mut Bx = &mut a;",
          "    r.n = r.n + 1;", "    *r = *r;", "    println(bx_show(&*r));"],
         ["(1)"], None),
        ([("new", "a"), ("mkst", "s", "a", "a"), ("wrf", "s", 0), ("readst", "s"), ("read", "a")],
         None, ["[(1) (0)]", "(0)"], "struct"),
        ([("new", "a"), ("mksome", "o", "a"), ("write", "a"), ("readen", "o"),
          ("unwrap", "b", "o"), ("read", "b")],
         None, ["some(0)", "(0)"], "enum"),
        ([("new", "a"), ("mkclo", "c", "a"), ("write", "a"), ("callc", "c"), ("read", "a")],
         ["    var a: Bx = Bx { n: 0, kids: Vec::new() };",
          "    val c = fn() -> str { return bx_show(&a); };", "    a.n = a.n + 1;",
          "    println(c());", "    println(bx_show(&a));"],
         ["(0)", "(1)"], "closure"),
        ([("new", "a"), ("mkrc", "h", "a"), ("cprc", "k", "h"), ("rccount", "h"),
          ("rcread", "k")],
         None, ["2", "(0)"], "rc"),
        ([("new", "a"), ("mkrc", "h", "a"), ("block", [("new", "b"), ("mkrc", "k", "b")]),
          ("rccount", "h")],
         None, ["1"], "rc"),
    ]
    for prog, body, out, _ext in cases:
        try:
            om.check(prog, frozenset())
        except om.Reject as e:
            print("  self-test: model rejects %s: %s" % (om.show(prog), e))
            bad = 1
            continue
        lowered = om.Machine(set()).run(prog)
        want = om.run_value(prog)
        if lowered != want:
            print("  self-test: lowered %r != value %r for %s" % (lowered, want, om.show(prog)))
            bad = 1
        got = [fmt_obs(o) for o in want]
        if got != out:
            print("  self-test: %s prints %r, expected %r" % (om.show(prog), got, out))
            bad = 1
        lines = translate(prog)
        if body is not None and lines != body:
            print("  self-test: translation of %s:\n    %s" % (om.show(prog), "\n    ".join(lines)))
            bad = 1
    # an rebind that changes the reference's type does not translate
    try:
        translate([("new", "a"), ("bor", "a", False), ("rebor", "a", True)])
        print("  self-test: r: &Bx rebound to &mut a was translated")
        bad = 1
    except Untranslatable:
        pass
    # markers and leak attribution
    got, missing = split_by_marker(["(1)", "#3", "#4", "(2)"], [3, 4, 5])
    if got != {3: ["(1)"], 4: [], 5: ["(2)"]} or missing != 5:
        print("  self-test: split_by_marker %r %r" % (got, missing))
        bad = 1
    text, spans = build_file([(7, ["    var a: Bx = %s;" % NEW])])
    ln = spans[7][0] + 1
    rep = "        40 bytes in      1 block(s): Vec_new <- m7, allocated at C:/x/own_t_1.fd:%d" % ln
    per, other = leak_sites("fid --leaks: 1 block(s)\n" + rep, spans, "own_t_1.fd")
    if 7 not in per or other:
        print("  self-test: leak attribution %r %r" % (per, other))
        bad = 1
    if "fn m7() {" not in text or 'println("#7");' not in text or "fn f2(p: &mut Bx) {" not in text:
        print("  self-test: generated file lacks m7, its marker or f2")
        bad = 1
    print("own_diff self-test: %s" % ("ok" if not bad else "FAILED"))
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fid", default=os.environ.get("FID", "release/fid.exe"))
    ap.add_argument("--size", type=int, default=3)
    ap.add_argument("--ext", default="all")
    ap.add_argument("--per", type=int, default=120,
                    help="programs per feature, spread over the accepted ones (0: none, -1: all)")
    ap.add_argument("--batch", type=int, default=60)
    ap.add_argument("--modes", default="run,leaks,checked")
    ap.add_argument("--rejected", type=int, default=0)
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--out", default=None, help="work folder (default: a new temporary one)")
    ap.add_argument("--strict", action="store_true",
                    help="also fail when fid rejects a program the model accepts")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    a.modes = [m for m in a.modes.split(",") if m]
    for m in a.modes:
        if m not in ("run", "leaks", "checked"):
            ap.error("unknown mode " + m)
    if a.ext == "all":
        feats = [("base", None)] + [(e, e) for e in om.EXTS]
    elif a.ext in ("none", ""):
        feats = [("base", None)]
    else:
        feats = [(e, None if e == "base" else e) for e in a.ext.split(",") if e]
        for f, e in feats:
            if e is not None and e not in om.EXTS:
                ap.error("unknown extension " + e)
    fid = a.fid
    if not os.path.isabs(fid):
        fid = os.path.abspath(fid)
    if not os.path.exists(fid) and not os.path.exists(fid + ".exe"):
        print("own_diff: no compiler at %s" % a.fid)
        return 2
    a.fid = fid
    work = a.out or tempfile.mkdtemp(prefix="own_diff_")
    os.makedirs(work, exist_ok=True)
    R = Runner(a, work)
    rep = {"fid": a.fid, "size": a.size, "modes": a.modes, "programs": [], "features": []}
    bad = 0
    t0 = time.time()
    for feat, ext in feats:
        fr = check_feature(R, feat, ext, rep)
        rep["features"].append(fr)
        print("own_diff: " + summary_line(fr))
        for key in ("fid_rejects", "mismatch", "leaks", "faults", "build_errors",
                    "other_leaks", "rejected_but_accepted"):
            for x in fr[key][:3]:
                print("    %s: %s" % (key, json.dumps(x)[:400]))
        if fr["mismatch"] or fr["leaks"] or fr["faults"] or fr["build_errors"] \
                or fr["other_leaks"] or fr["rejected_but_accepted"] \
                or (a.strict and fr["fid_rejects"]):
            bad = 1
    with open(os.path.join(work, "own_diff.json"), "w", encoding="utf-8") as f:
        json.dump(rep, f, indent=1)
    print("own_diff: %d fid processes, %.0f s; report %s"
          % (R.processes, time.time() - t0, os.path.join(work, "own_diff.json")))
    return bad


if __name__ == "__main__":
    sys.exit(main())
