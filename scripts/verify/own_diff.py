#!/usr/bin/env python3
"""own_diff.py - the differential check of the compiler's ownership lowering
against the model of scripts/verify/own_model.py (VF11).

own_model.py enumerates every program of its calculus up to a size, checks
it with the reference's rules and runs the accepted ones two ways (counted
cells, plain values). This script takes the accepted programs, translates
each into Fides (a box is `struct Bx { n: i64, kids: Vec<Bx> }`, so a copy
is a Vec_share/__own_dup and a write is copy-on-write in compiler/lower.fd's
LOWER_RC lowering), and runs them through the compiler:

  run      `fid run`                 (the interpreter, compiler/interp.fd)
  leaks    `fid run --leaks`         (C, the leak report of the debug allocator)
  checked  `fid run --checked-alloc` (C, a use after free or double free faults)

For every program, what it prints must be what the model's value run reads
(the values, and for Rc the counts: `h.count()` is the model's number of
live handles); `--leaks` must report no block left that was allocated on a
line of the program; `--checked-alloc` must not fault. A program the model
accepts and `fid` rejects is listed too (the model or the compiler is wrong
about the rules), and with --rejected N, N programs per feature that the
model rejects for a borrow or escape reason are each checked alone: `fid`
must reject them as well.

Programs are batched: one Fides file holds --batch programs, each a
function `m<k>()`, called in turn by `main`, each followed by a line `#<k>`.
A batch that does not build is split until the programs `fid` rejects are
found (each by `fid check`).

    python3 scripts/verify/own_diff.py --fid release/fid.exe [--size 3]
        [--ext all|none|a,b] [--per 120] [--batch 60] [--modes run,leaks,checked]
        [--rejected 0] [--out DIR] [--self-test]

--self-test checks the translator alone (no fid): fixed programs give the
expected Fides text and expected output. FID_HOME is passed through (the
stdlib the compiler reads). One fid process runs at a time.

Exit status: 0 when every program agrees, leaks nothing and does not fault
(and, with --rejected, every rejected program is rejected; with --strict,
fid also accepts every program the model accepts: a rejection is a
stricter compiler, not a safety failure); 1 otherwise; 2 on a usage or
tool error.
"""
