#!/usr/bin/env python3
"""Generate stdlib/brotli_dict.fd: the brotli static dictionary as Fides data.

The dictionary (122,784 bytes, RFC 7932 Appendix A) is google/brotli's
c/common/dictionary.bin (MIT licence, Copyright Google Inc.). It is stored
as base64 text in 40 string literals of 4096 characters (3072 bytes) each,
so stdlib/brotli.fd can read any byte without decoding the whole thing and
native executables carry it with them (they run without the stdlib).

Usage:
    python scripts/gen-brotli-dict.py path/to/dictionary.bin [out.fd]

The output defaults to stdlib/brotli_dict.fd next to this script. The script
decodes what it wrote back to bytes and checks they equal the input.
"""
import base64
import hashlib
import os
import re
import sys

DICT_SIZE = 122784
DICT_SHA256 = "20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70"
CHUNK = 3072  # bytes per literal: 4096 base64 characters, no padding


def generate(data: bytes) -> str:
    chunks = [data[i:i + CHUNK] for i in range(0, len(data), CHUNK)]
    out = []
    out.append("// The brotli static dictionary (RFC 7932 Appendix A), as data.\n")
    out.append("//\n")
    out.append("// GENERATED by scripts/gen-brotli-dict.py from google/brotli's\n")
    out.append("// c/common/dictionary.bin. Do not edit by hand.\n")
    out.append("//\n")
    out.append("// Copyright Google Inc. Distributed under the MIT licence (the brotli\n")
    out.append("// project's licence: https://github.com/google/brotli/blob/master/LICENSE).\n")
    out.append("//\n")
    out.append(f"// {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()},\n")
    out.append(f"// stored as base64 in {len(chunks)} literals of {CHUNK} bytes\n")
    out.append(f"// ({CHUNK * 4 // 3} characters) each; the last holds {len(chunks[-1])} bytes.\n")
    out.append("// stdlib/brotli.fd decodes the bytes it needs (dict_byte).\n")
    out.append("\nmodule brotli_dict;\n\n")
    out.append(f"/// Size of the dictionary in bytes.\npub fn brotli_dict_size() -> i64 {{ return {len(data)}; }}\n\n")
    out.append(f"/// Bytes held by each chunk (every chunk but the last).\npub fn brotli_dict_chunk_bytes() -> i64 {{ return {CHUNK}; }}\n\n")
    out.append("/// Chunk `i` (0-based) of the dictionary as base64 text, or \"\" past\n")
    out.append("/// the end.\n")
    out.append("pub fn brotli_dict_chunk(i: i64) -> str {\n")
    # binary-search style: split the if-chain in two halves of 20
    half = (len(chunks) + 1) // 2
    out.append(f"    if i < {half} {{\n")
    for k in range(half):
        b64 = base64.b64encode(chunks[k]).decode("ascii")
        out.append(f"        if i == {k} {{ return \"{b64}\"; }}\n")
    out.append("        return \"\";\n    }\n")
    for k in range(half, len(chunks)):
        b64 = base64.b64encode(chunks[k]).decode("ascii")
        out.append(f"    if i == {k} {{ return \"{b64}\"; }}\n")
    out.append("    return \"\";\n}\n")
    return "".join(out)


def check(text: str, data: bytes) -> None:
    lits = re.findall(r'return "([A-Za-z0-9+/=]+)";', text)
    back = b"".join(base64.b64decode(s) for s in lits)
    if back != data:
        raise SystemExit("round trip FAILED: generated data differs from input")


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    data = open(sys.argv[1], "rb").read()
    if len(data) != DICT_SIZE:
        raise SystemExit(f"expected {DICT_SIZE} bytes, got {len(data)}")
    digest = hashlib.sha256(data).hexdigest()
    if digest != DICT_SHA256:
        print(f"warning: sha256 {digest} is not the known {DICT_SHA256}")
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "stdlib", "brotli_dict.fd")
    text = generate(data)
    check(text, data)
    with open(out_path, "w", newline="\n", encoding="ascii") as f:
        f.write(text)
    print(f"wrote {out_path}: {len(text)} characters, round trip ok")


if __name__ == "__main__":
    main()
